
#While loop
number = 20

while number <= 25:
    print(number)
    number += 1


num = 1     # initialize
while num <= 10: # condition
    print(num)
    num += 1  #Increment/Decrement


num1 = 50   # initialize
while num1 >= 40: # condition
    print(num1)
    num1 -= 1  #Increment/Decrement


#For Loop
for x in range(5):
    print(x)

for y in range(1,11):
    print(y)


for x in range(11, 88, 3):
    print(x)