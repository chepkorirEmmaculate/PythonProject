#arithmetic operations - Simple Calculations
x = 90
y = 5

print(x  +  y)
print(x  *  y)
print(x  -  y)
print(x  /  y)
print(x  %  y)  #modulus - returns reminder after division


#Comparison Operators - Compare values and return boolean
num1 = 45
num2 = 15

print(num1 < num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2)  #Equal to
print(num1 != num2)  #Not equal


#Assignment Operators - Assign/Store values in variable
number = 80
print(number)

##Operator Precedence
number += 2 #addition assignment
print(number)

#Logical Operators - and, or, not

print( 100==50 and 60 < 80 )
print( 100==50 or 60 < 80 )
print( not(100==50 and 60 < 80) )